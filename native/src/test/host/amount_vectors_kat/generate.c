//   cc -std=c99 -I native/src/main/jni/digibytewallet-core -o /tmp/amount_vectors \
//      native/src/test/host/amount_vectors_kat/generate.c \
//   && /tmp/amount_vectors > native/src/test/host/amount_vectors_kat/vectors.txt

