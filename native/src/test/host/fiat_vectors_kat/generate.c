// Vectors for BRFiatAmount.h: the header's answers for the rate (BRFiatRateFromDouble), both
// conversions, dollar text (parse and format) and the send screen's two amount fields, on a fixed
// corpus, so a platform's mirror can be held to exactly what the core computes. Android's
// UsdCentsVectorsTest reads this file on the host JVM; nothing on that side computes an answer of
// its own for a line here.
//
// Like the core's vectors/tx-rows/, these are the header written down, not an independent source:
// the independent expectations are the hand-written and Python-derived values in fiat_amount_kat.
// fiat_vectors_kat/run.sh checks this file is current, and that the naive double conversion
// (-DFIAT_VIA_DOUBLE_UNFIXED) writes a different one.
//
// The core has no vectors/fiat/ yet; until it does, this generator and its output live in
// Android (native/src/test/host/fiat_vectors_kat/), built against the pinned submodule.
//
// Regenerate, from the android repo root:
//   cc -std=c99 -I native/src/main/jni/digibytewallet-core -o /tmp/fiat_vectors \
//      native/src/test/host/fiat_vectors_kat/generate.c -lm \
//   && /tmp/fiat_vectors > native/src/test/host/fiat_vectors_kat/vectors.txt

#include "BRFiatAmount.h"

#include <float.h>
#include <inttypes.h>
#include <math.h>
#include <string.h>

#define I64MAX INT64_C(9223372036854775807)

static uint64_t bitsOf(double x)
{
    uint64_t b;
    memcpy(&b, &x, sizeof(b));
    return b;
}

static double fromBits(uint64_t b)
{
    double x;
    memcpy(&x, &b, sizeof(x));
    return x;
}

// Text as one token: "..." with every byte outside '!'..'~', and '"' and '\', written \xHH.
static void quoted(const char *s, size_t len)
{
    putchar('"');
    for (size_t i = 0; i < len; i++) {
        unsigned char c = (unsigned char)s[i];
        if (c < 0x21 || c > 0x7e || c == '"' || c == '\\') printf("\\x%02x", c);
        else putchar(c);
    }
    putchar('"');
}

// A deterministic 64-bit LCG (Knuth's MMIX constants), so the corpus is the same on every host.
static uint64_t g_lcg = UINT64_C(0x2545f4914f6cdd1d);
static uint64_t next(void)
{
    g_lcg = g_lcg * UINT64_C(6364136223846793005) + UINT64_C(1442695040888963407);
    return g_lcg;
}

// ---- the price corpus -----------------------------------------------------------------------

#define MAX_PRICES 600
static double g_price[MAX_PRICES];
static size_t g_nPrice = 0;
static void price(double x) { if (g_nPrice < MAX_PRICES) g_price[g_nPrice++] = x; }

static void rateLine(double x)
{
    BRFiatRate r;
    printf("rate %016" PRIx64 " %.17g ", bitsOf(x), x);
    if (BRFiatRateFromDouble(x, &r)) printf("%" PRIu64 " %" PRId32 "\n", r.digits, r.exp);
    else printf("-\n");
}

static void c4sLine(int64_t sats, double x)
{
    BRFiatRate r;
    int64_t cents;
    if (! BRFiatRateFromDouble(x, &r)) return;
    printf("c4s %" PRId64 " %016" PRIx64 " ", sats, bitsOf(x));
    if (BRFiatCentsForSats(sats, r, &cents)) printf("%" PRId64 "\n", cents);
    else printf("-\n");
}

static void s4cLine(int64_t cents, double x)
{
    BRFiatRate r;
    int64_t sats;
    if (! BRFiatRateFromDouble(x, &r)) return;
    printf("s4c %" PRId64 " %016" PRIx64 " ", cents, bitsOf(x));
    if (BRFiatSatsForCents(cents, r, &sats)) printf("%" PRId64 "\n", sats);
    else printf("-\n");
}

static void parseLine(const char *s, size_t len)
{
    int64_t cents;
    printf("parse ");
    quoted(s, len);
    if (BRUsdCentsParse(s, len, &cents)) printf(" %" PRId64 "\n", cents);
    else printf(" -\n");
}

static void formatLine(int64_t cents)
{
    char out[BR_FIAT_TEXT_BUFSIZE];
    size_t n = BRUsdCentsFormat(cents, out, sizeof(out));
    printf("format %" PRId64 " ", cents);
    quoted(out, n);
    printf("\n");
}

static void previewLine(const char *dgb, double x)
{
    char out[BR_FIAT_TEXT_BUFSIZE];
    size_t n = BRFiatPreviewForDgb(dgb, strlen(dgb), x, out, sizeof(out));
    printf("preview ");
    quoted(dgb, strlen(dgb));
    printf(" %016" PRIx64 " ", bitsOf(x));
    quoted(out, n);
    printf("\n");
}

static void dgbTextLine(const char *usd, double x)
{
    char out[BR_FIAT_TEXT_BUFSIZE];
    size_t n = BRFiatDgbTextFor(usd, strlen(usd), x, out, sizeof(out));
    printf("dgbtext ");
    quoted(usd, strlen(usd));
    printf(" %016" PRIx64 " ", bitsOf(x));
    quoted(out, n);
    printf("\n");
}

int main(void)
{
    size_t i, j, named, feedFrom, feedTo, pow2From, pow2To, randFrom;

    printf("# BRFiatAmount.h vectors: the header's answers, written down. Generated by\n");
    printf("# native/src/test/host/fiat_vectors_kat/generate.c; do not edit (fiat_vectors_kat checks it is current).\n");
    printf("# A price is the 16 hex digits of its IEEE-754 bits (the %%.17g beside a rate is for reading only).\n");
    printf("# Text is one token: \"...\", every byte outside '!'..'~' (and '\"', '\\\\') written \\xHH; it is UTF-8.\n");
    printf("# rate <price bits> <%%.17g> <digits> <exp>    the rate is digits x 10^exp; '-' = not a usable price\n");
    printf("# c4s <sats> <price bits> <cents>             BRFiatCentsForSats; '-' = refused\n");
    printf("# s4c <cents> <price bits> <sats>             BRFiatSatsForCents; '-' = refused\n");
    printf("# parse <text> <cents>                        BRUsdCentsParse; '-' = not a whole number of cents\n");
    printf("# format <cents> <text>                       BRUsdCentsFormat\n");
    printf("# preview <dgb text> <price bits> <text>      BRFiatPreviewForDgb (\"\" = nothing to show)\n");
    printf("# dgbtext <usd text> <price bits> <text>      BRFiatDgbTextFor (\"\" = nothing to show)\n");

    // Named prices: feed-shaped ones first, then the ones that break a naive or JDK-17 reading.
    price(0.00612); price(0.0123); price(0.01); price(0.1); price(0.001); price(2e-3); price(0.4);
    price(0.007891); price(0.0099); price(0.00999); price(0.012345); price(0.15); price(1.0); price(2.0);
    price(1e6); price(1000001.0); price(1.5e6); price(8e6);
    price(0.2); price(0.3); price(0.30000000000000004); price(1.0 / 3); price(2.0 / 3);
    price(1e22); price(1e23); price(2e23);
    price(ldexp(1.0, -24)); price(ldexp(1.0, -44)); price(ldexp(1.0, -20)); price(ldexp(1.0, -54));
    price(5e-324); price(1e-323); price(DBL_MIN); price(nextafter(DBL_MIN, 0.0)); price(DBL_MAX);
    price(nextafter(DBL_MAX, 0.0)); price(nextafter(1.0, 2.0)); price(nextafter(1.0, 0.0));
    // JDK-4511638: JDK 17's Double.toString prints these with digits that change the value.
    price(2.82879384806159e17); price(1.387364135037754e18); price(1.45800632428665e17);
    price(2.0e-3); price(1.0e-5); price(1.1e-5);
    price(9007199254740993.0);   // 2^53 + 1 reads as 2^53
    // The shortest candidate falls exactly on a rounding boundary: an even significand takes it
    // (round half to even), an odd one does not and needs one more digit.
    price(1.8014398509481988e16); price(1.801439850948199e16);
    price(1.8014398509482012e16); price(1.801439850948201e16);
    price(1.8014398509482028e16); price(1.801439850948203e16);
    named = g_nPrice;

    // Feed-shaped: up to five significant digits, dollars per DGB from a cent down to 10^-7.
    feedFrom = g_nPrice;
    for (i = 0; i < 120; i++) {
        char buf[32];
        uint64_t m = next() >> 33;
        int digits = 1 + (int)((next() >> 40) % 5), exp = -2 - (int)((next() >> 40) % 6);
        uint64_t mod = 1;
        for (int k = 0; k < digits; k++) mod *= 10;
        m = 1 + m % (mod - 1);
        snprintf(buf, sizeof(buf), "%" PRIu64 "e%d", m, exp - digits + 1);
        price(strtod(buf, NULL));
    }
    feedTo = g_nPrice;

    // Every power of two from 2^-60 to 2^60: the one case where the rounding interval is wider
    // above than below, so the nearest decimal can miss and the next one up hit.
    pow2From = g_nPrice;
    for (int e = -60; e <= 60; e++) price(ldexp(1.0, e));
    pow2To = g_nPrice;

    // Arbitrary positive finite doubles across the whole exponent range.
    randFrom = g_nPrice;
    for (i = 0; i < 150; i++) {
        uint64_t b = next() & UINT64_C(0x7fffffffffffffff);
        if (((b >> 52) & 0x7ff) == 0x7ff) b &= ~(UINT64_C(1) << 62);   // not NaN or infinity
        if (b == 0) b = 1;
        price(fromBits(b));
    }

    // ---- rate ----
    for (i = 0; i < g_nPrice; i++) rateLine(g_price[i]);
    rateLine(0.0); rateLine(-0.0); rateLine(-1.0); rateLine(-5e-324); rateLine(NAN);
    rateLine(INFINITY); rateLine(-INFINITY);

    // ---- conversions ----
    {
        static const int64_t sats[] = { 0, 1, 5, 50000000, 100000000, 150000000, 250000000, 750000000,
                                        123456789, 10000000000LL, 100000000000000LL, 1000000000000000000LL,
                                        9007199254740993LL, INT64_C(6148914691236517204),
                                        INT64_C(6148914691236517205), I64MAX, -1, INT64_MIN };
        static const int64_t cents[] = { 0, 1, 4, 5, 12, 20, 29, 100, 500, 1234, 123456789,
                                         9007199254740993LL, I64MAX, -1, INT64_MIN };
        for (i = 0; i < g_nPrice; i++) {
            int use = i < named || (i >= feedFrom && i < feedFrom + 40) ||
                      (i >= pow2From && i < pow2To && (i - pow2From) % 6 == 0) ||
                      (i >= randFrom && i < randFrom + 20);
            if (! use) continue;
            for (j = 0; j < sizeof(sats) / sizeof(sats[0]); j++) c4sLine(sats[j], g_price[i]);
            for (j = 0; j < sizeof(cents) / sizeof(cents[0]); j++) s4cLine(cents[j], g_price[i]);
        }
    }

    // ---- dollar text ----
    {
        static const char *t[] = {
            "40", "40.00", "40.50", "40.5", "0.09", ".5", "1.00", "100000.00", "  0.29 ", "0", "5.", "0.00",
            "00.01", "007", "\t7\n", "\r\n5\f\v", " 5 ",
            "1.005", "1.0000", "0.001", "2.675", "40.500", "1.50", "1.5", "1.",
            "1,50", "0,1", "1,234.50", "1,234,567.5", "1,234", "1,2,3", "1,234,567", ",1.5", "1.5,",
            ",.", ",", ",,", "1,,5", "1,,5.0", "1.2,3", ",5", "5,", "1,5,", "1.,5",
            "1e5", "1E2", "NaN", "Infinity", "+1", "-1", "-0", "1.5f", "0x10", "1e-2", "1_000",
            "", "   ", ".", "..", "..5", "5..", "abc", "1.2.3", "1 000", "$5", "5$", "1 .5", "\t", "\n",
            "92233720368547758.07", "92233720368547758.08", "92233720368547758.7", "92233720368547758",
            "92233720368547759", "99999999999999999999", "9223372036854775807",
            "00000000000000000000000000000001", "000000000000000000000000000000001",
            "00,000,000,000,000,000,000,000,000,000.01", "000,000,000,000,000,000,000,000,000,000.01",
            "0000000000000000000000000000000,1", "000000000000000000000000000000,1",
            "                                        5",
            // Not whitespace to the core (Kotlin's trim() once took them): Unicode spaces and the
            // ASCII separators U+001C..U+001F. Non-ASCII digits are not here: a platform maps them
            // to ASCII before the core reads the text (iOS FiatText.asciiDigits, UsdCents.asciiDigits),
            // which a line of the core's answers cannot express; UsdCentsTest covers the mapping.
            "\xc2\xa0" "5", "5\xc2\xa0", "\xe2\x80\x83" "5", "\x1c" "5", "5\x1f", "\xd9\xab",
            "\xff", "5\xff",
        };
        for (i = 0; i < sizeof(t) / sizeof(t[0]); i++) parseLine(t[i], strlen(t[i]));
        parseLine("1\0" "5", 3);      // an embedded NUL is a character, not the end
        {
            static char big[1001];
            memset(big, '9', 1000);
            parseLine(big, 1000);
        }
    }
    {
        static const int64_t c[] = { 0, 1, 9, 10, 99, 100, 101, 5000, 123456, 10000000, 123456789012LL,
                                     9007199254740993LL, I64MAX, -1, -5, -100, -123456, INT64_MIN };
        for (i = 0; i < sizeof(c) / sizeof(c[0]); i++) formatLine(c[i]);
    }

    // ---- the two amount fields ----
    {
        static const char *dgb[] = {
            "0", "1", "0.5", "1.5", "2.5", "100", "0,5", "1,234.5", "1234.5", "0.29", "0.00000001",
            "0.000000001", "1e2", "1E-8", "+5", "-0", "-1", "", "abc", "1,2,3", " 7 ",
            "92233720368.54775807", "92233720368.54775808", "10000000000", "123456789.12345678",
        };
        static const char *usd[] = {
            "0", "0.01", "0.04", "0.20", "0.29", "5", "12.34", "0,5", "0.50", "1,234.56", "1234567.89",
            "1.005", "-5", "1e2", "", "abc", "92233720368547758.07", "92233720368.54",
        };
        static const double bad[] = { 0.0, -0.0, -1.0, NAN, INFINITY, -INFINITY };
        for (i = 0; i < g_nPrice; i++) {
            if (! (i < named || (i >= feedFrom && i < feedFrom + 15))) continue;
            for (j = 0; j < sizeof(dgb) / sizeof(dgb[0]); j++) previewLine(dgb[j], g_price[i]);
            for (j = 0; j < sizeof(usd) / sizeof(usd[0]); j++) dgbTextLine(usd[j], g_price[i]);
        }
        for (i = 0; i < sizeof(bad) / sizeof(bad[0]); i++) {
            previewLine("1", bad[i]); dgbTextLine("5", bad[i]);
        }
    }
    (void)feedTo;
    return 0;
}
