//
//  wallet_copy_guards_kat_main.c
//
//  Host KAT: no copy or compare in BRWallet.c's DigiDollar transfer builder, or in the core's test.c
//  transaction-equality helpers, is passed a NULL pointer, not even for 0 bytes. memcpy and memcmp with
//  a NULL argument are undefined behaviour whatever the length; glibc declares them nonnull, so UBSan
//  stops on such a call on Linux. glibc_nonnull.h (force-included by run.sh) gives macOS the same
//  declarations, so a Mac run sees the same reports.
//
//  Two groups of cases:
//
//    dd_send_*   BRWalletCreateDigiDollarTransfer, from the LIVE BRWallet.c #included below (so the
//                KAT can place coin records the wallet's own bookkeeping never makes). A DigiDollar
//                coin record or a fee coin record that names an output with a NULL, zero-length
//                script is put FIRST in the wallet's lists; the builder must pass over it with no
//                sanitizer report and build the same bytes it builds without that record. The two
//                script copies in the builder are now guarded by scriptLen > 0, but neither can be
//                reached with an empty script today: a DigiDollar coin is taken only once
//                BRDigiDollarOutputAmount gives it an amount, which needs its 34-byte P2TR script,
//                and a fee coin only once _BRWalletOutputSignable accepts its script, which needs a
//                non-NULL script of 22, 23, 25 or 34 bytes. So these cases pass on the unguarded
//                builder too; they hold the invariant (an empty script never reaches the copy, and a
//                record naming one changes nothing), and run.sh's source gate holds the guards. They do
//                walk the record: an unguarded builder whose two filters let a NULL script through
//                stops on each copy in these cases (checked by hand at authoring time).
//
//    tx_equal_*  test.c's BRTxOutputEqual, BRTxInputEqual and BRTransactionEqual (with BRBytesEqual,
//                the helper they now share), extracted from the core's test.c by run.sh into
//                test_equal_extract.c. test.c itself does not build against this core (it is the
//                upstream suite, left behind by API changes), so the functions are compiled on their
//                own. An unsigned input's signature is NULL with sigLen 0, and an input or output
//                added with no script has a NULL script; the comparison arm
//                -DTEST_TX_EQUAL_UNFIXED=1 (the memcmp without the n == 0 test) must stop on a UBSan
//                nonnull report in exactly the cases that compare one.
//
//  One case per process: `wallet_copy_guards_kat <case>` prints PASS:/FAIL: lines and
//  `RESULT <case> pass|fail`; `list` prints the case names.
//
//  Exit code 0 = every check passed; 1 = a check failed.

